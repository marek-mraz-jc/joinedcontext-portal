#!/usr/bin/env python3
"""The Portal's permission map (T-3916): which page action reaches which route, the rule
tests/authz_matrix.yaml holds that route to, and the roles that pass it.

The page actions come from the code graph: every UI or SDK call `.cg/links` joins to a route
handler (`cg build --fg` first). The rule and the roles come from the authorization matrix. Red when
a route a page calls has no matrix row, or a matrix row names no route the graph knows: then the map
and the matrix disagree, and one of them is wrong.

  dev/permission-map.py            write docs/analysis/portal-permission-map.md, check both ways
  dev/permission-map.py --check    check only
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
MATRIX = ROOT / "tests" / "authz_matrix.yaml"
PAGE = ROOT / "docs" / "analysis" / "portal-permission-map.md"

# A UI or SDK call, the route it reaches, and the decisions the handler reaches in six hops.
QUERIES = """\
MATCH (u:Symbol)-[:USES]->(c:Channel {channel:'http'})<-[:PROVIDES]-(h:Symbol) WHERE u.lang = 'typescript' RETURN DISTINCT u.file, u.name, c.key, h.path ORDER BY c.key, u.file, u.name;
MATCH (h:Symbol)-[:PROVIDES]->(c:Channel {channel:'http'}) RETURN DISTINCT c.key ORDER BY c.key;
MATCH (h:Symbol)-[:PROVIDES]->(c:Channel {channel:'http'}) MATCH (h)-[:CALLS|DISPATCHES*1..6]->(g:Symbol) WHERE g.path STARTS WITH 'joinedcontext_portal::permissions::' AND g.name IN ['check', 'may', 'may_in', 'may_read', 'may_read_in', 'may_read_project', 'may_read_manifest', 'may_read_space', 'may_write_status_field', 'may_propose_anything', 'administers_organization', 'require_organization_admin', 'is_organization_member', 'within_own_rights', 'keeps_an_administrator', 'keeps_an_administrator_after'] RETURN DISTINCT h.path, g.name ORDER BY h.path, g.name;
"""


def norm(key: str) -> str:
    """A route key as `.cg` normalises it: every path parameter `{}`, no trailing slash."""
    key = re.sub(r"\{[^}]*\}", "{}", key)
    return key[:-1] if key.endswith("/") and not key.endswith(" /") else key


def tables(output: str) -> list[list[list[str]]]:
    """The rows of each statement of `cg q` output, headers dropped."""
    found: list[list[list[str]]] = []
    rows: list[list[str]] | None = None
    header = False
    for line in output.splitlines():
        if line.startswith("### Q"):
            rows, header = [], True
            found.append(rows)
        elif rows is None or not line.strip() or re.match(r"\d+ rows", line):
            continue
        # cg's own words, never a substring a row may hold (T-4021)
        elif line.startswith(("hint:", "... truncated at ")) or "output stops at" in line:
            sys.exit(f"cg: {line}")
        elif header:
            header = False
        else:
            rows.append([cell.strip() for cell in line.split(" | ")])
    return found


def matrix() -> tuple[list[str], dict[str, dict]]:
    data = yaml.safe_load(MATRIX.read_text())
    return data["roles"], {row["route"]: row for row in data["routes"]}


def check(calls, providers: set[str], roles, rows) -> tuple[dict[str, str], list[str]]:
    """The matrix row of each provider key, and every disagreement between the two."""
    problems, row_of = [], {}
    for route in rows:
        verb, path = route.split(" ", 1)
        candidates = [norm(f"{verb} {path}"), norm(f"{verb} /api/v1{path}")]
        known = [c for c in candidates if c in providers]
        if not known:
            problems.append(f"matrix row names no route the graph knows: {route}")
        for key in known:
            row_of[key] = route
    for file, name, key, _ in calls:
        if key not in row_of:
            problems.append(f"{file}::{name} calls {key}, which has no matrix row")
    return row_of, problems


def render(calls, decisions, roles, rows, row_of) -> str:
    lines = [
        "# Portal permission map",
        "",
        "Generated by `dev/permission-map.py` from the code graph (`.cg/links` joins each UI and App SDK",
        "call to its axum handler) and `tests/authz_matrix.yaml` (the rule each route is held to and the",
        "status each role gets). Do not edit by hand: change the code or the matrix and run the script.",
        "",
        "Columns: the page (file under `ui/src` or `sdk/src`) and the action (the function that makes",
        "the call), the route, the matrix rule, the roles the matrix lets through (`allow`) and those it",
        "answers `404` (the matrix's note on the row says whether that is a fixture without the object",
        "after the check passed, or a refusal kept as `404`), and the decisions of `crate::permissions`",
        "the handler reaches within six calls (`—`: none; the rule names the other door: the session",
        "alone, a bearer of a workload, an App's edge token, a signature).",
        "",
        "| Page | Action | Route | Rule | allow | 404 | Decision reached |",
        "|---|---|---|---|---|---|---|",
    ]
    for file, name, key, handler in calls:
        row = rows[row_of[key]]
        passing = [role for role, cell in zip(roles, row["expect"]) if cell == "allow"]
        hidden = [role for role, cell in zip(roles, row["expect"]) if cell == 404]
        page = re.sub(r"^(ui|sdk)/src/", "", file)
        reached = ", ".join(sorted(decisions.get(handler, ()))) or "—"
        lines.append(
            f"| `{page}` | `{name}` | `{key}` | {row['rule']} | {', '.join(passing) or '—'}"
            f" | {', '.join(hidden) or '—'} | {reached} |"
        )
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    run = subprocess.run(["cg", "q", "--max-rows", "10000", "-"], input=QUERIES, cwd=ROOT,
                         capture_output=True, text=True, check=False)
    if run.returncode != 0:
        print(run.stdout + run.stderr, file=sys.stderr)
        return 2
    calls, provided, reached = tables(run.stdout)
    decisions: dict[str, set[str]] = {}
    for handler, name in reached:
        decisions.setdefault(handler, set()).add(name)
    roles, rows = matrix()
    row_of, problems = check(calls, {key for (key,) in provided}, roles, rows)
    for p in problems:
        print(p)
    if not problems and argv[1:] != ["--check"]:
        PAGE.parent.mkdir(parents=True, exist_ok=True)
        PAGE.write_text(render(calls, decisions, roles, rows, row_of))
    print(f"permission-map: {len(calls)} calls, {len(problems)} problem(s)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
