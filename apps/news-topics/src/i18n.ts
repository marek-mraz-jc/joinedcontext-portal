export type TranslationKey = keyof typeof DICTIONARY.en;

/** The page's language: `?lang=` in the address or in its `#topics?` part, else the browser's, else English. */
export function getLanguage(): Lang {
  const hash = window.location.hash;
  for (const query of [window.location.search, hash.slice(hash.indexOf("?") + 1)]) {
    const asked = new URLSearchParams(query).get("lang");
    if (asked === "fi" || asked === "en" || asked === "sv") return asked;
  }
  const browser = navigator.language.toLowerCase().slice(0, 2);
  return browser === "fi" || browser === "sv" ? browser : "en";
}

export function localeOf(lang: Lang): "fi-FI" | "en-GB" | "sv-FI" {
  return ({ fi: "fi-FI", en: "en-GB", sv: "sv-FI" } as const)[lang];
}

export function formatDate(date: Date | string | null | undefined, lang: Lang): string {
  if (!date) return "";
  const d = typeof date === "string" ? new Date(date) : date;
  if (Number.isNaN(d.getTime())) return "";
  const opts: Intl.DateTimeFormatOptions = {
    timeZone: ZONE,
    dateStyle: "medium",
    timeStyle: "short",
  };
  return new Intl.DateTimeFormat(localeOf(lang), opts).format(d);
}

export function formatPercent(
  fraction: number,
  lang: Lang,
  maximumFractionDigits = 1,
): string {
  return new Intl.NumberFormat(localeOf(lang), {
    style: "percent",
    maximumFractionDigits,
  }).format(fraction);
}

/** The word in the language, each `{slot}` filled from `slots`; a slot not given stays visible. */
export function t(key: TranslationKey, lang: Lang, slots: Record<string, string | number> = {}): string {
  return DICTIONARY[lang][key].replace(/\{(\w+)\}/g, (whole, name: string) => (name in slots ? String(slots[name]) : whole));
}
